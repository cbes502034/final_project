def bar(score):
    color = "var(--bad)" if score < 60 else ("var(--warn)" if score < 80 else "var(--accent)")
    return ('<div class="bar"><i style="width:%d%%;background:%s"></i></div>' % (score, color))


def body():
    before = sum(s[1] for s in SCORES) / len(SCORES)
    after = sum(s[2] for s in SCORES) / len(SCORES)
    low_before = sum(1 for s in SCORES if s[1] < 60)
    low_after = sum(1 for s in SCORES if s[2] < 60)
    h = '<section class="cover"><div>'
    h += '<div class="eyebrow">FAMBUDGET · USER REVIEW · 2026-10-19</div>'
    h += "<h1>家庭記帳<br>使用者評分與改善建議</h1>"
    h += ('<p class="lede">換成一般使用者——一位家長、一位孩子——在正式網站上把每個功能實際用過一遍，'
          "看結果對不對、找不找得到、說法清不清楚、手機好不好用，逐項給分。"
          "低於 60 分的功能先退回測試工程師修正、上線驗證，再重新評分。</p>")
    h += '<div class="kpis">'
    for v, k in (("%d" % len(SCORES), "評分的功能"), ("%.1f → %.1f" % (before, after), "平均分數"),
                 ("%d → %d" % (low_before, low_after), "低於 60 分的功能"), ("%d" % min(s[2] for s in SCORES), "修正後最低分")):
        h += '<div class="kpi"><div class="v" style="font-size:15pt">%s</div><div class="k">%s</div></div>' % (v, k)
    h += "</div></div>"
    h += '<div class="meta">'
    for k, v in (("網站", "https://fambudget-web.onrender.com"), ("角色", "家長 邱冠文、子女 冠文_user（同一個家庭、家長照看子女）"),
                 ("看的範圍", "24 個畫面 × 375／768／1280 三種寬度；實際記帳、AI 解析、產生建議、設預算、邀請家人"),
                 ("評分方式", "結果對不對 40％、好不好找（沒有重複）25％、說法清楚 20％、手機 15％")):
        h += "<b>%s</b><span>%s</span>" % (e(k), e(v))
    h += "</div></section>"

    h += '<h2><span class="n">01</span>每個功能的分數</h2>'
    rows = []
    for name, b, a, why in SCORES:
        rows.append([e(name), '<span class="%s">%d</span>' % ("bad" if b < 60 else "soft", b),
                     "<b>%d</b>" % a, bar(a), e(why)])
    h += table(["功能", "修正前", "修正後", "", "使用者的感受（修正後）"], rows, num_cols=(1, 2),
               widths=["17%", "8%", "8%", "12%", "55%"])
    h += '<p class="small">修正前 0 分＝當時沒有這個功能。紅字是低於 60 分（集合線）的功能，第 2 節逐項說明。</p>'

    h += '<h2 class="break"><span class="n">02</span>修正前低於 60 分的功能</h2>'
    h += ("<p>這 %d 項在使用者觀點下都有實際的功能問題，所以照流程退回測試工程師：找原因、修正、推送、"
          "等 Render 自動部署，再回到正式網站重新驗證，最後才重新評分。</p>" % low_before)
    for name, score, pain, fix, verify in sorted(LOW, key=lambda x: x[1]):
        h += "<h3>%s　<span class=\"bad\">%d</span> → <span class=\"ok\">%d</span></h3>" % (
            e(name), score, next(s[2] for s in SCORES if s[0] == name))
        h += table(["", ""], [["使用者遇到什麼", e(pain)], ["改善方案（已完成）", e(fix)], ["修正後線上實測", e(verify)]],
                   widths=["20%", "80%"]).replace("<thead><tr><th class=\"\"></th><th class=\"\"></th></tr></thead>", "")

    h += '<h2 class="break"><span class="n">03</span>逐頁盤點：重複與多餘</h2>'
    h += "<p>同一個畫面上，同一件事只放一個入口；跟這一頁無關的東西不放。逐頁檢查會數出同名的按鈕與指向同一頁的連結，再一頁一頁看截圖確認。</p>"
    h += table(["頁面", "發現", "處理"], [[e(a), e(b), e(c)] for a, b, c in DEDUP], widths=["18%", "48%", "34%"])
    h += '<div class="note">修正後重新檢查：各頁重複的按鈕歸零（每一列各一個「修改／刪除」是正常的）；手機總覽的常用功能剩「帳本、家庭成員、個人資料、使用說明、換主題、登出」。</div>'

    h += '<h2><span class="n">04</span>還可以更好（下一輪建議）</h2>'
    h += "<p>修正後每個功能都在 60 分以上。下面是使用起來還不夠順、但不影響正確性的地方，依優先順序排列。</p>"
    h += table(["優先", "功能", "建議"], [[tag(p, "p2" if p == "P2" else "p3"), e(f), e(t)] for p, f, t in NEXT],
               widths=["8%", "14%", "78%"])

    h += '<h2><span class="n">05</span>這一輪的循環</h2><ul>'
    for t in ("使用者觀點逐頁操作 → 找到個人資料頁打不開、重複入口、指錯的連結",
              "退回測試工程師：本機重現、修正、加回歸測試（768 個全過）",
              "推送到「冠文」分支 → Render 自動部署 → 前端資源版本號升到 v=162",
              "回到正式網站重新檢查改過的頁面：無錯誤、無重複、三種寬度無溢出",
              "回到使用者觀點重新評分（第 1 節）"):
        h += "<li>%s</li>" % e(t)
    h += "</ul>"
    h += '<div class="foot">產生方式：python report/qa/build_user_report.py；搭配《家庭記帳 線上測試報告》一起看。</div>'
    return h


if __name__ == "__main__":
    print(build("家庭記帳 使用者評分與改善建議", body(), os.path.join(HERE, "家庭記帳_使用者評分與改善建議.pdf")))
