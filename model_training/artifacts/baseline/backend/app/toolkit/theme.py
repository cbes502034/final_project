"""
介面主題：使用者選哪一套外觀。

負責人：成員1（認證）——主題存在 users.theme，由 PATCH /api/auth/me 修改

===========================================================================
一句話
===========================================================================
主題只是一個字串 id。**後端不畫任何東西**，只負責「存」和「擋掉不在清單裡的值」。

===========================================================================
為什麼後端還要驗證
===========================================================================
前端會把這個 id 放進 <html data-theme="…">。雖然瀏覽器不會把屬性值
當程式執行，但資料庫裡出現清單外的值，下一個讀它的地方（報表、匯出、
別的前端）就得各自猜該怎麼辦。**進資料庫之前就擋掉**，其他地方都不用防。

換膚完全在瀏覽器裡發生，後端的負擔就是多存一個欄位：
不用新表、不用新路由、不增加任何運算。

===========================================================================
清單要跟前端對齊
===========================================================================
正本在 frontend/js/data.js 的 themes；每一套在 frontend/css/themes.css
都有一個 [data-theme="id"]。三邊有測試對齊（test_主題清單三邊一致）。

===========================================================================
怎麼用
===========================================================================
    from app.toolkit import theme

    if body.theme is not None:
        user.theme = theme.clean_theme(body.theme)   # 不在清單裡 → ValueError → 回 422
"""

from __future__ import annotations

__all__ = ["THEMES", "DEFAULT", "clean_theme"]

#: 可以選的主題。順序就是主題設定頁上的順序。
THEMES = ("paper", "sky", "tech", "literary", "pop", "girly", "cute", "art")

#: 沒選過的人用這個。users.theme 的預設值。
DEFAULT = "paper"


def clean_theme(value: object) -> str:
    """只收清單裡的 id，其他一律丟 ValueError。

    不做大小寫轉換、不去空白——前端送的一定是清單裡的字，
    送錯代表程式有問題，應該被看見而不是被默默修正。

    >>> clean_theme("sky")
    'sky'
    >>> clean_theme("Sky")
    Traceback (most recent call last):
    ...
    ValueError: 沒有這個主題
    """
    if not isinstance(value, str) or value not in THEMES:
        raise ValueError("沒有這個主題")
    return value
